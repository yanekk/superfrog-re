"""Summarises results/runs.csv into results/SUMMARY.md: the main table (exits / clean exits per
executor and condition), faithful-check passes, cost, determinism. Run from experiments/route-follower."""
import csv
from collections import defaultdict

latest = {}
for r in csv.DictReader(open('results/runs.csv')):
    # A rerun replaces an earlier row of the same run.
    latest[(r['level'], r['exec'], r['cond'], r['label'])] = r
rows = list(latest.values())
main = [r for r in rows if r['label'] == '']
execs = [e for e in ["fixed", "A", "B1", "B2", "B23", "B3"] if any(r['exec'] == e for r in main)]
conds = ["P0", "P1", "P2", "P3:1", "P3:2", "P3:5", "P3:20", "P3o:5", "P4o", "P4e:200:2",
         "P5:0", "P5:2", "P5o:0", "P6", "P6e"]
names = {
    "P0": "own timing (original)", "P1": "engine, no lag", "P2": "app start",
    "P3:1": "late 1 (engine)", "P3:2": "late 2 (engine)", "P3:5": "late 5 (engine)",
    "P3:20": "late 20 (engine)", "P3o:5": "late 5 (original)", "P4o": "original's lag frames (engine)",
    "P4e:200:2": "2 lag frames / 200 (engine)", "P5:0": "easy (engine)", "P5:2": "hard (engine)",
    "P5o:0": "easy (original)", "P6": "whole-game leg (original)", "P6e": "whole-game leg (engine)",
}
cell = defaultdict(list)
for r in main:
    cell[(r['exec'], r['cond'])].append(r)

out = ["# Route follower — summary (generated by tools/summarize.py)", ""]
out.append("Each cell: exits / clean exits (no life lost) / levels run. Clean = owner's second column.")
out.append("")
out.append("| Condition | " + " | ".join(execs) + " |")
out.append("|---|" + "---|" * len(execs))
tot = defaultdict(lambda: [0, 0, 0])
for c in conds:
    cells = []
    for e in execs:
        rs = cell.get((e, c), [])
        ex = sum(r['exit'] == 'true' for r in rs)
        cl = sum(r['clean'] == 'true' for r in rs)
        if c != "P0":
            t = tot[e]
            t[0] += ex; t[1] += cl; t[2] += len(rs)
        cells.append(f"{ex}/{cl}/{len(rs)}" if rs else "—")
    out.append(f"| {names[c]} | " + " | ".join(cells) + " |")
out.append("| **all perturbed (not P0)** | " + " | ".join(f"{tot[e][0]}/{tot[e][1]}/{tot[e][2]}" for e in execs) + " |")
out.append("")

out.append("## Faithful check (`verify`) on recordings made on the original")
out.append("")
out.append("| Executor | " + " | ".join(["P0", "P3o:5", "P6"]) + " |")
out.append("|---|---|---|---|")
for e in execs:
    cs = []
    for c in ["P0", "P3o:5", "P6"]:
        rs = cell.get((e, c), [])
        p = sum(r['verify'].startswith('pass') for r in rs)
        cs.append(f"{p}/{len(rs)}" if rs else "—")
    out.append(f"| {e} | " + " | ".join(cs) + " |")
out.append("")

out.append("## Cost and length (exits only)")
out.append("")
out.append("| Executor | median engine frames per frame played | median secs per run | median frames vs route (P0 ref) |")
out.append("|---|---|---|---|")
ref = {r['level']: int(r['exit_frame']) for r in main if r['exec'] == 'fixed' and r['cond'] == 'P0' and r['exit'] == 'true'}


def med(v):
    v = sorted(v)
    return v[len(v) // 2] if v else float('nan')


for e in execs:
    rs = [r for r in main if r['exec'] == e and r['exit'] == 'true']
    epf = med([float(r['eng_per_frame']) for r in rs])
    secs = med([float(r['secs']) for r in rs])
    ratio = med([int(r['exit_frame']) / ref[r['level']] for r in rs if r['level'] in ref])
    out.append(f"| {e} | {epf:.0f} | {secs:.1f} | {ratio:.2f} |")
out.append("")

out.append("## Per level, perturbed conditions (exits / runs)")
out.append("")
levels = sorted({r['level'] for r in main}, key=lambda l: "W1-1 W1-4 W2-1 W3-2 W5-2 W6-1 W6-2 W4-3".split().index(l))
out.append("| Level | " + " | ".join(execs) + " |")
out.append("|---|" + "---|" * len(execs))
for lv in levels:
    cs = []
    for e in execs:
        rs = [r for r in main if r['level'] == lv and r['exec'] == e and r['cond'] != 'P0']
        cs.append(f"{sum(r['exit'] == 'true' for r in rs)}/{len(rs)}")
    out.append(f"| {lv} | " + " | ".join(cs) + " |")
out.append("")

out.append("## Determinism (P1, seed 1)")
out.append("")
out.append("| Level | Executor | main run hash | repeat | 1 thread |")
out.append("|---|---|---|---|---|")
for lv in levels:
    for e in ["B2", "B23"]:
        h = [r['rec_hash'] for r in main if r['level'] == lv and r['exec'] == e and r['cond'] == 'P1']
        rep = [r['rec_hash'] for r in rows if r['level'] == lv and r['exec'] == e and r['label'] == 'det-repeat']
        t1 = [r['rec_hash'] for r in rows if r['level'] == lv and r['exec'] == e and r['label'] == 'det-threads1']
        if rep or t1:
            same = lambda x: ("same" if x and h and x[0] == h[0] else ("DIFFERENT" if x else "—"))
            out.append(f"| {lv} | {e} | {h[0] if h else '—'} | {same(rep)} | {same(t1)} |")
open('results/SUMMARY.md', 'w').write("\n".join(out) + "\n")
print("\n".join(out))
