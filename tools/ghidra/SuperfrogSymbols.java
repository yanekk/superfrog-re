// Post-script for tools/re_ghidra_import.py: applies re/symbols.toml to a Superfrog program,
// decompiles every function and exports the names given in Ghidra, so they can go back into
// symbols.toml.
//
// Args: <symbols.tsv> <out prefix> <chunk id>
//   symbols.tsv: hunk \t offset \t name \t kind \t size \t note   (offsets decimal)
//   writes <prefix>.c (decompilation) and <prefix>.ghidra-names.toml (names made in Ghidra)
//@category Superfrog
import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.CodeUnit;
import ghidra.program.model.listing.Function;
import ghidra.program.model.mem.MemoryBlock;
import ghidra.program.model.symbol.SourceType;
import ghidra.program.model.symbol.Symbol;
import ghidra.program.model.symbol.SymbolIterator;

import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class SuperfrogSymbols extends GhidraScript {
    private static final Pattern HUNK_BLOCK = Pattern.compile("^[A-Z]+_(\\d+)$");

    /** Start of each hunk: blocks named CODE_00, BSS_01 ... by the Amiga loader, else the one raw block. */
    private List<MemoryBlock> hunkBlocks() {
        List<MemoryBlock> out = new ArrayList<>();
        MemoryBlock first = null;
        for (MemoryBlock b : currentProgram.getMemory().getBlocks()) {
            Matcher m = HUNK_BLOCK.matcher(b.getName());
            if (m.matches()) {
                int n = Integer.parseInt(m.group(1));
                while (out.size() <= n) out.add(null);
                out.set(n, b);
            } else if (first == null && b.isInitialized()) {
                first = b;
            }
        }
        if (out.isEmpty() && first != null) out.add(first);
        return out;
    }

    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        Path tsv = Path.of(args[0]);
        String prefix = args[1];
        List<MemoryBlock> hunks = hunkBlocks();
        Set<String> ours = new HashSet<>();
        int applied = 0;
        for (String line : Files.readAllLines(tsv)) {
            if (line.isBlank()) continue;
            String[] f = line.split("\t", -1);
            int hunk = Integer.parseInt(f[0]);
            long offset = Long.parseLong(f[1]);
            String name = f[2], kind = f[3], note = f[5];
            if (hunk >= hunks.size() || hunks.get(hunk) == null) {
                printerr("no block for hunk " + hunk + " (" + name + ")");
                continue;
            }
            Address a = hunks.get(hunk).getStart().add(offset);
            ours.add(name);
            if (kind.equals("func")) {
                if (getInstructionAt(a) == null) disassemble(a);
                Function fn = getFunctionAt(a);
                if (fn == null) fn = createFunction(a, name);
                if (fn != null) fn.setName(name, SourceType.IMPORTED);
                else createLabel(a, name, true, SourceType.IMPORTED);
            } else {
                createLabel(a, name, true, SourceType.IMPORTED);
            }
            if (!note.isEmpty()) setPlateComment(a, note);
            applied++;
        }
        println("applied " + applied + " symbols");

        // decompilation of every function
        DecompInterface dec = new DecompInterface();
        dec.openProgram(currentProgram);
        int n = 0;
        try (PrintWriter w = new PrintWriter(prefix + ".c")) {
            w.println("// Ghidra decompilation, generated by tools/re_ghidra_import.py. Never commit (DESIGN 2.3).");
            for (Function fn : currentProgram.getFunctionManager().getFunctions(true)) {
                if (monitor.isCancelled()) break;
                DecompileResults r = dec.decompileFunction(fn, 60, monitor);
                w.println();
                w.println("// " + fn.getName() + " @ " + where(hunks, fn.getEntryPoint()));
                if (r != null && r.decompileCompleted()) w.print(r.getDecompiledFunction().getC());
                else w.println("// decompile failed: " + (r == null ? "?" : r.getErrorMessage()));
                n++;
            }
        }
        dec.dispose();
        println("decompiled " + n + " functions");

        // round trip: names a person gave in Ghidra, in symbols.toml form
        int exported = 0;
        try (PrintWriter w = new PrintWriter(prefix + ".ghidra-names.toml")) {
            w.println("# Names given in Ghidra that re/symbols.toml does not have yet. Review, then paste.");
            SymbolIterator it = currentProgram.getSymbolTable().getAllSymbols(true);
            while (it.hasNext()) {
                Symbol s = it.next();
                if (s.getSource() != SourceType.USER_DEFINED || ours.contains(s.getName())) continue;
                int hunk = hunkOf(hunks, s.getAddress());
                if (hunk < 0) continue;
                boolean fn = getFunctionAt(s.getAddress()) != null;
                w.println();
                w.println("[[sym]]");
                w.println("exe = \"" + args[2] + "\"");
                w.println("hunk = " + hunk);
                w.println(String.format("offset = 0x%x", s.getAddress().subtract(hunks.get(hunk).getStart())));
                w.println("name = \"" + s.getName() + "\"");
                w.println("kind = \"" + (fn ? "func" : "data") + "\"");
                if (!fn) w.println("size = 1   # set the real size");
                CodeUnit cu = currentProgram.getListing().getCodeUnitAt(s.getAddress());
                String c = cu == null ? null : cu.getComment(CodeUnit.PLATE_COMMENT);
                w.println("note = \"" + (c == null ? "" : c.replace("\"", "'").replace("\n", " ")) + "\"");
                exported++;
            }
        }
        println("exported " + exported + " names made in Ghidra");
    }

    private int hunkOf(List<MemoryBlock> hunks, Address a) {
        for (int i = 0; i < hunks.size(); i++)
            if (hunks.get(i) != null && hunks.get(i).contains(a)) return i;
        return -1;
    }

    private String where(List<MemoryBlock> hunks, Address a) {
        int h = hunkOf(hunks, a);
        return h < 0 ? a.toString() : String.format("h%d+$%x", h, a.subtract(hunks.get(h).getStart()));
    }
}
