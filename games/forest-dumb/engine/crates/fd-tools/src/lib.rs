//! Shell side (DESIGN §3.1): takes the game's two disks out of the owner's zips into `build/` and
//! writes the inventory, and reads one file from them unpacked, in memory (`game_file`). The zips are only ever read, and nothing is written until both disks have
//! been read whole, so a bad zip never leaves a partial result.

mod locate;
mod unpack;

use std::fmt::Write as _;
use std::path::{Component, Path, PathBuf};

use amiga_disk::ofs::OfsImage;
use amiga_disk::sha1::sha1_hex;
use amiga_disk::{ADF_SIZE, zip};

pub use locate::{disk_dir, locate, main_checkout, zip_paths};
pub use unpack::{game_file, unpack};

/// The engine build a bug recording is stamped with and its replay checks (`build.rs`): the
/// version and a hash of the engine's sources, the same in `fd-app` and `fd-conform`.
pub const ENGINE_BUILD: &str = env!("FD_ENGINE_BUILD");

/// One extracted file of the inventory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InventoryFile {
    pub disk: u8,
    pub name: String,
    pub size: u32,
    pub sha1: String,
}

/// Extract both disks into `out` (created if missing): the two ADFs as `out/disk<N>.adf` and every
/// file in `out/files/disk<N>/<name>`, sorted by disk then name. Never writes outside `out`, and
/// `out` must be inside a folder named `build` (DESIGN §5.2).
pub fn extract(dir: &Path, out: &Path) -> Result<Vec<InventoryFile>, String> {
    check_target(out)?;
    let zips = zip_paths(dir)?;
    let adfs = [read_adf(&zips[0])?, read_adf(&zips[1])?];

    let mut inventory = Vec::new();
    let mut writes: Vec<(PathBuf, Vec<u8>)> = Vec::new();
    for (i, (adf, zip_path)) in adfs.iter().zip(&zips).enumerate() {
        let disk = i as u8 + 1;
        let bad = |e: String| format!("{}: {e}", describe(zip_path));
        let image = OfsImage::parse(adf).map_err(|e| bad(format!("its ADF: {e}")))?;
        let names: Vec<String> = image.files().map(|(n, _)| n.to_string()).collect();
        for name in names {
            let bytes = image
                .read_file(&name)
                .map_err(|e| bad(format!("{name:?} on its ADF: {e}")))?;
            let rel = entry_path(&name).map_err(bad)?;
            inventory.push(InventoryFile {
                disk,
                size: bytes.len() as u32,
                sha1: sha1_hex(&bytes),
                name,
            });
            writes.push((out.join(format!("files/disk{disk}")).join(rel), bytes));
        }
        writes.push((out.join(format!("disk{disk}.adf")), adf.clone()));
    }
    for (path, bytes) in &writes {
        let parent = path.parent().expect("every target sits under out");
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        std::fs::write(path, bytes).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    inventory.sort_by(|a, b| (a.disk, &a.name).cmp(&(b.disk, &b.name)));
    Ok(inventory)
}

/// The committed inventory: a header naming the two zips and their SHA-1s, then one tab-separated
/// line a file (disk, name, size, SHA-1). Names may hold spaces; a tab cannot be typed into one.
pub fn inventory_text(dir: &Path, files: &[InventoryFile]) -> Result<String, String> {
    let mut text = String::from(
        "# Forest Dumb Forever: every file of both disks. Generated by `cargo run -p fd-tools -- extract`.\n",
    );
    for (i, path) in zip_paths(dir)?.iter().enumerate() {
        let bytes = std::fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?;
        let name = path.file_name().unwrap_or_default().to_string_lossy();
        writeln!(text, "# zip {}: {name} sha1 {}", i + 1, sha1_hex(&bytes)).unwrap();
    }
    text.push_str("# disk\tname\tsize\tsha1\n");
    for f in files {
        writeln!(text, "{}\t{}\t{}\t{}", f.disk, f.name, f.size, f.sha1).unwrap();
    }
    Ok(text)
}

/// The seatbelt: a mistyped `--out` cannot land on the owner's zips or in the tracked tree.
fn check_target(out: &Path) -> Result<(), String> {
    let inside_build = out
        .components()
        .any(|c| matches!(c, Component::Normal(n) if n == "build"));
    let climbs = out.components().any(|c| c == Component::ParentDir);
    if !inside_build || climbs {
        return Err(format!(
            "{}: refusing to write there: the output must be inside a folder named build, with no ..",
            out.display()
        ));
    }
    Ok(())
}

/// A file's path on the disk as a path under its output folder. AmigaDOS allows a file to be named
/// `..`, and a damaged directory can hold anything, so the name is not trusted to stay inside.
pub fn entry_path(name: &str) -> Result<PathBuf, String> {
    let mut path = PathBuf::new();
    for part in name.split('/') {
        if part.is_empty() || part == "." || part == ".." || part.contains(['\\', '\0']) {
            return Err(format!(
                "the file name {name:?} would not stay in the output folder"
            ));
        }
        path.push(part);
    }
    Ok(path)
}

/// The one ADF inside a zip, whole and the right size, or an error naming the zip and its checksum.
pub fn read_adf(path: &Path) -> Result<Vec<u8>, String> {
    let bytes = std::fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let bad = |e: String| format!("{}: {e}", describe_bytes(path, &bytes));
    // One byte over the limit, so an oversized image reaches the size check below and says so.
    let entries = zip::read_entries(&bytes, |n| n.to_lowercase().ends_with(".adf"), ADF_SIZE + 1)
        .map_err(bad)?;
    let [entry] = &entries[..] else {
        return Err(bad(format!("it holds {} ADFs, not one", entries.len())));
    };
    if entry.bytes.len() != ADF_SIZE {
        return Err(bad(format!(
            "“{}” inside it is {} bytes, not the {ADF_SIZE} of a whole disk",
            entry.name,
            entry.bytes.len()
        )));
    }
    Ok(entry.bytes.clone())
}

fn describe(path: &Path) -> String {
    match std::fs::read(path) {
        Ok(bytes) => describe_bytes(path, &bytes),
        Err(_) => path.display().to_string(),
    }
}

fn describe_bytes(path: &Path, bytes: &[u8]) -> String {
    format!("{} (sha1 {})", path.display(), sha1_hex(bytes))
}
