"""toolkit/tools/hunk_listing.py on a hand-built hunk executable: no disks, no game."""
import os, struct, sys, unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hunk_listing as L

HEADER, CODE, DATA, RELOC32, END = 0x3F3, 0x3E9, 0x3EA, 0x3EC, 0x3F2


def longs(*values):
    return b''.join(struct.pack('>I', v) for v in values)


def exe():
    """Two hunks: code `jmp $4.l` relocated into the data hunk, then a nop; data of two longs."""
    code = bytes.fromhex('4ef900000004' '4e71')
    data = bytes(range(8))
    return (longs(HEADER, 0, 2, 0, 1, 2, 2)
            + longs(CODE, 2) + code + longs(RELOC32, 1, 1, 2, 0, END)
            + longs(DATA, 2) + data + longs(END))


SYMS = '''[[sym]]
exe = "x"
hunk = 0
offset = 0
name = "start"
kind = "func"
note = "the entry"

[[sym]]
exe = "x"
hunk = 1
offset = 4
name = "table_b"
kind = "table"
size = 4
'''


class Parse(unittest.TestCase):
    def test_hunks_lie_back_to_back_and_relocate(self):
        e = L.load_exe(exe())
        self.assertFalse(e.raw)
        self.assertEqual([(h.kind, h.base, h.size) for h in e.hunks], [('CODE', 0, 8), ('DATA', 8, 8)])
        self.assertEqual(e.relocs, {(0, 2): (1, 4)})
        self.assertEqual(int.from_bytes(e.hunks[0].data[2:6], 'big'), 12)
        self.assertEqual(e.locate(9), (1, 1))
        self.assertIsNone(e.locate(100))

    def test_a_declared_but_absent_hunk_becomes_empty(self):
        data = exe().replace(longs(HEADER, 0, 2, 0, 1, 2, 2), longs(HEADER, 0, 3, 0, 2, 2, 2, 16))
        e = L.parse_exe(data)
        self.assertEqual([h.kind for h in e.hunks], ['CODE', 'DATA', 'ABSENT'])
        self.assertEqual(e.hunks[2].size, 64)

    def test_anything_else_is_a_raw_region(self):
        e = L.load_exe(bytes.fromhex('4e714e75'))
        self.assertTrue(e.raw)
        self.assertEqual(e.hunks[0].size, 4)


class Listing(unittest.TestCase):
    def test_references_print_as_symbols_and_xrefs_name_the_caller(self):
        e = L.load_exe(exe())
        text = L.listing('x', e, L.load_symbols('t.toml', SYMS), xrefs=True)
        self.assertIn('; func — the entry\nstart:\n', text)
        self.assertRegex(text, r'00000000  4ef90000000c +jmp +table_b')
        self.assertIn('\ntable_b:\n          ; xref: start (abs)\n', text)
        self.assertIn('dc.b $04,$05,$06,$07', text)
        self.assertIn('generated by hunk_listing.py', text)

    def test_an_entry_resyncs_the_sweep_after_data_in_code(self):
        # A word of data ($4ef9, jmp's opcode) then two nops: the sweep reads `jmp` over the nops.
        code = bytes.fromhex('4ef9' '4e71' '4e71' '4e75')
        e = L.load_exe(longs(HEADER, 0, 1, 0, 0, 2) + longs(CODE, 2) + code + longs(END))
        self.assertNotIn('00000002  4e71', L.listing('x', e, []))
        text = L.listing('x', e, [], entries=[2])
        self.assertIn('00000002  4e71', text)
        self.assertIn('00000004  4e71', text)

    def test_a_byte_var_leaves_the_sweep_on_the_next_even_address(self):
        # A byte variable, a spare byte, then a function: nop, rts. Read from the odd byte, the
        # sweep took `$004e` as a word and swallowed the function's first byte.
        code = bytes.fromhex('01' '00' '4e71' '4e75' '4e71')
        e = L.load_exe(longs(HEADER, 0, 1, 0, 0, 2) + longs(CODE, 2) + code + longs(END))
        syms = L.load_symbols('t.toml', '[[sym]]\nexe = "x"\nhunk = 0\noffset = 0\nname = "flag"\n'
                                        'kind = "var"\nsize = 1\n\n'
                                        '[[sym]]\nexe = "x"\nhunk = 0\noffset = 2\nname = "fn"\nkind = "func"\n')
        text = L.listing('x', e, syms)
        self.assertIn('flag:\n00000000  01                    dc.b $01\n'
                      '00000001  00                    dc.b $00\n', text)
        self.assertIn('fn:\n00000002  4e71', text)
        self.assertIn('00000004  4e75', text)
        self.assertNotIn('falls inside', text)
        # with no symbol after it the sweep is back on a word all the same
        self.assertIn('00000002  4e71', L.listing('x', e, syms[:1]))
        self.assertNotIn('h0+$2:', text)

    def test_a_symbol_past_its_hunk_is_refused(self):
        bad = SYMS.replace('offset = 4', 'offset = 0x100').replace('size = 4', 'size = 1')
        with self.assertRaisesRegex(L.SymbolError, r'table_b: offset \$100 is past hunk 1'):
            L.listing('x', L.load_exe(exe()), L.load_symbols('t.toml', bad))


class Symbols(unittest.TestCase):
    def test_duplicates_and_overlaps_name_their_line(self):
        dup = '[[sym]]\nexe = "x"\nhunk = 0\noffset = 0\nname = "a"\nkind = "func"\n' \
              '[[sym]]\nexe = "x"\nhunk = 0\noffset = 2\nname = "a"\nkind = "func"\n'
        with self.assertRaisesRegex(L.SymbolError, r't:7: duplicate name a'):
            L.load_symbols('t', dup)


if __name__ == '__main__':
    unittest.main()
